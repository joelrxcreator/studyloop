// Schneller Bilder-Durchlauf aller Bildschirme (hell/dunkel). Nutzt denselben Supabase-Nachbau.
import { createMock } from './mock-supabase.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT || 'playwright');
const SHOTS = process.env.SHOTS || 'shots';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM || undefined });
for (const theme of (process.env.THEMES || 'light,dark').split(',')) {
  const W = Number(process.env.W || 390), H = Number(process.env.H || 844);
  const mock = createMock();
  const ctx = await browser.newContext({ viewport: { width: W, height: H }, deviceScaleFactor: 2, isMobile: W < 700, hasTouch: true, locale: 'de-DE', timezoneId: 'Europe/Berlin', colorScheme: theme });
  await ctx.route('https://ibmhbjwkkgjuzyztakmg.supabase.co/**', mock.handle);
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  p.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errs.push(m.text()); });
  await p.clock.setFixedTime(new Date('2026-10-21T10:40:00+02:00'));
  await p.goto(process.env.BASE || 'http://localhost:8080/');
  const s = async (n) => { await p.waitForTimeout(450); await p.screenshot({ path: `${SHOTS}/${theme}-${W}-${n}.png` }); };
  await s('00-welcome');
  await p.getByRole('button', { name: 'Konto erstellen' }).click();
  await s('01-signup');
  await p.fill('input[name=email]', 'joel@example.org');
  await p.fill('input[name=password]', 'geheim123');
  await p.locator('[data-submit]').click();
  await p.waitForSelector('[data-preset]');
  await s('02-semester');
  await p.locator('[data-preset]').click();
  await s('03-timetable');
  await p.locator('[data-tt="et1-ek3-b"]').click();
  await s('04-count');
  await p.locator('[data-count="fresh"]').click();
  await s('04b-push');
  await p.locator('[data-skip]').click();
  await p.waitForSelector('.tabbar');
  // ein paar Einträge
  await s('05-today');
  await p.locator('.occ').first().click();
  await s('06-occ-sheet');
  await p.locator('[data-star="2"]').click();
  await p.locator('[data-note]').fill('Kapitel 5 nochmal anschauen');
  await p.locator('.sheet-h [data-close]').click();
  await p.waitForTimeout(400);
  await p.locator('.occ [data-act="done"]').nth(1).click();
  await s('07-today-after');
  await p.locator('#main').evaluate((e) => e.scrollTo(0, 400));
  await s('07b-today-scrolled');
  await p.locator('[data-tab="week"]').click();
  await s('08-week');
  await p.locator('#main').evaluate((e) => e.scrollTo(0, 2000));
  await s('08b-week-bottom');
  await p.locator('[data-tab="subjects"]').click();
  await s('09-subjects');
  await p.locator('[data-act="subject"]').first().click();
  await s('10-subject');
  if (await p.locator('.page [data-act="back"]').count()) await p.locator('.page [data-act="back"]').click();
  await p.locator('[data-tab="exams"]').click();
  await s('11-exams');
  await p.locator('.nav [data-act="newExam"]').click();
  await s('12-exam-new');
  await p.locator('.sheet-h [data-close]').click();
  await p.waitForTimeout(400);
  await p.locator('[data-act="settings"]').click();
  await s('13-settings');
  await p.locator('.page [data-act="editTT"]').click();
  await s('14-tt-editor');
  await p.locator('.page.in').last().locator('[data-act="editSeries"]').first().click();
  await s('15-series');
  console.log(theme, 'Fehler:', errs.length ? errs : 'keine');
  await ctx.close();
}
await browser.close();
